import PizZip from 'pizzip';
import { saveAs } from 'file-saver';
import { ACCESS_LABELS, EVENT_LABELS, BACKUP_TYPE_LABELS, fileStamp, allowedRolesText } from './reportFormat';

const cell = (value) => {
  if (value == null) return '';
  const text = value instanceof Date ? value.toISOString() : Array.isArray(value) ? value.join('; ') : String(value);
  return /[",\n\r]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
};

// BOM so Excel opens UTF-8 correctly.
const toCsv = (headers, rows) => '﻿' + [headers, ...rows].map((r) => r.map(cell).join(',')).join('\r\n');

const pct = (v) => (v == null ? 'NOT_MEASURED' : Number(v).toFixed(2));

/**
 * Builds one CSV per report table and downloads them as a single zip.
 */
export const exportSystemReportCsv = (report) => {
  const { meta, checks, findings, availability, activity, users, security, rbac, backups, integrity } = report;
  const zip = new PizZip();
  const add = (name, headers, rows) => zip.file(name, toCsv(headers, rows));

  add('00_report_info.csv', ['Field', 'Value'], [
    ['Report', 'DRIMS System Activity & Status Report'],
    ['Period from', meta.from],
    ['Period to', meta.to],
    ['Timezone', meta.timezone],
    ['Environment', meta.environment],
    ['Generated at', meta.generatedAt],
    ['Generated by', `${meta.generatedBy?.name || ''} (${meta.generatedBy?.role || ''})`],
    ['Instrumentation active since', meta.instrumentationSince || 'NOT_MEASURED'],
  ]);

  add('01_summary_checks.csv', ['Section', 'Check', 'Status', 'Detail'],
    checks.map((c) => [c.section, c.label, c.status, c.detail]));

  add('02_findings.csv', ['Severity', 'Finding', 'Detail'],
    findings.map((f) => [f.severity, f.title, f.detail]));

  add('03_uptime_summary.csv', ['Metric', 'Value'], [
    ['Status', availability.status],
    ['Uptime %', pct(availability.uptimePercent)],
    ['Measured from', availability.measuredFrom || 'NOT_MEASURED'],
    ['Measured to', availability.measuredTo || 'NOT_MEASURED'],
    ['Up minutes', availability.upMinutes ?? ''],
    ['Expected minutes', availability.expectedMinutes ?? ''],
    ['Downtime minutes', availability.downtimeMinutes ?? ''],
    ['Outages', availability.outages?.length ?? ''],
    ['Longest outage (min)', availability.longestOutageMinutes ?? ''],
    ['Restarts', availability.restarts ?? ''],
    ...(availability.notMeasuredRanges || []).map((r) => ['Not measured range', `${r.from} → ${r.to}${r.reason ? ` (${r.reason})` : ''}`]),
  ]);

  add('04_uptime_daily.csv', ['Date', 'Uptime %', 'Up minutes', 'Expected minutes'],
    availability.daily.length
      ? availability.daily.map((d) => [d.day, d.measured ? pct(d.uptimePercent) : 'NOT_MEASURED', d.upMinutes, d.expectedMinutes])
      : []);

  add('05_outages.csv', ['From', 'To', 'Duration (min)'],
    (availability.outages || []).map((o) => [o.from, o.to, o.durationMinutes]));

  add('06_submissions_daily.csv', ['Date', 'Student documents', 'Proposals', 'Books', 'Letters', 'Total'],
    activity.submissions.daily.map((d) => [d.day, d.studentDocuments, d.proposals, d.books, d.letters, d.total]));

  add('07_student_documents_by_type.csv', ['Type', 'Count'],
    activity.submissions.studentDocumentsByType.map((r) => [r.type, r.count]));

  add('08_direct_messages_daily.csv', ['Date', 'Sent', 'Read by recipient', 'Unread'],
    activity.messages.daily.map((d) => [d.day, d.sent, d.readByRecipient, d.sent - d.readByRecipient]));

  add('09_direct_messages_by_sender_role.csv', ['Sender role', 'Messages sent'],
    activity.messages.sentByRole.map((r) => [r.role, r.count]));

  add('10_logins_by_role.csv', ['Role', 'Logins', 'Unique users'],
    activity.logins.byRole.map((r) => [r.role, r.logins, r.uniqueUsers]));

  add('11_logins_daily.csv', ['Date', 'Logins'], activity.logins.daily.map((d) => [d.day, d.logins]));

  add('12_security_events_by_type.csv', ['Event', 'Code', 'Count'],
    security.measured
      ? Object.keys(EVENT_LABELS).map((k) => [EVENT_LABELS[k], k, security.totals[k] || 0])
      : Object.keys(EVENT_LABELS).map((k) => [EVENT_LABELS[k], k, 'NOT_MEASURED']));

  add('13_security_events_daily.csv', ['Date', 'Role denials', 'Unauthenticated', 'Failed logins', 'Rate limited'],
    security.daily.map((d) => [d.day, d.denied, d.unauthenticated, d.failedLogins, d.rateLimited]));

  add('14_denied_endpoints.csv', ['Event', 'Method', 'Endpoint', 'Count'],
    security.deniedByEndpoint.map((r) => [r.type, r.method, r.endpoint, r.count]));

  add('15_failed_logins_by_ip.csv', ['IP address', 'Failed logins'],
    security.failedLoginsByIp.map((r) => [r.ipAddress, r.failedLogins]));

  add('16_session_controls.csv', ['Control', 'Value'], [
    ['Token lifetime', security.session.tokenLifetime],
    ['Remember-me lifetime', security.session.rememberMeLifetime],
    ['Server-side revocation', security.session.serverSideRevocation ? 'Enabled' : 'Disabled'],
    ['API rate limit', `${security.session.rateLimits.api.limit} / ${security.session.rateLimits.api.windowMinutes} min (${security.session.rateLimits.api.keyedBy})`],
    ['Login rate limit', `${security.session.rateLimits.login.limit} / ${security.session.rateLimits.login.windowMinutes} min (${security.session.rateLimits.login.keyedBy})`],
    ['Login rate limit per IP', `${security.session.rateLimits.loginPerIp.limit} / ${security.session.rateLimits.loginPerIp.windowMinutes} min`],
    ['Logouts (tokens revoked)', security.session.logouts],
    ['Deactivations (sessions revoked)', security.session.deactivationRevocations],
  ]);

  add('17_rbac_matrix.csv', ['Method', 'Path', 'Authenticated', 'Allowed roles', 'Auditor read-only guard', 'Access'],
    rbac.routes.map((r) => [r.method, r.path, r.authenticated ? 'Yes' : 'No', allowedRolesText(r), r.readOnlyGuard ? 'Yes' : 'No', ACCESS_LABELS[r.access]]));

  add('18_backups.csv', ['Performed at', 'Type', 'Dump', 'Off-site', 'Atlas mirror', 'Verify', 'Verify details', 'Size (GB)', 'Duration (s)', 'Archive', 'Recorded by', 'Notes'],
    backups.records.map((r) => [
      r.performedAt, BACKUP_TYPE_LABELS[r.type] || r.type, r.status, r.offsiteStatus || '', r.mirrorStatus || '', r.verifyStatus || '',
      r.verifyDetails || '', r.sizeGb ?? '', r.durationSeconds ?? '', r.archiveName || '', r.recordedByName || '', r.notes || '',
    ]));

  add('19_data_integrity.csv', ['Check', 'Count'], [
    ['Student documents without stored file', integrity.studentDocumentsWithoutContent],
    ['Letters without stored file', integrity.lettersWithoutContent],
  ]);

  add('20_users_summary.csv', ['Metric', 'Value'], [
    ['As of', users.asOf],
    ['Total accounts', users.total],
    ['Active', users.active],
    ['Deactivated', users.deactivated],
    ['New in period', users.newInPeriod],
    ['Students (total)', users.students.total],
    ['Students (active)', users.students.active],
    ['Students (new in period)', users.students.newInPeriod],
    ['Staff (total)', users.staff.total],
    ['Staff (active)', users.staff.active],
    ['Staff (new in period)', users.staff.newInPeriod],
    ['Signed in during period', activity.logins.uniqueUsers],
  ]);

  add('21_users_by_role.csv', ['Role', 'Total', 'Active', 'Deactivated', 'New in period', 'Signed in during period'],
    users.byRole.map((r) => [r.role, r.total, r.active, r.deactivated, r.newInPeriod, activity.logins.byRole.find((l) => l.role === r.role)?.uniqueUsers || 0]));

  const ext = availability.external;
  add('22_external_uptime_summary.csv', ['Metric', 'Value'], !ext || ext.status === 'NOT_MEASURED'
    ? [['Status', 'NOT_MEASURED'], ['Configured', ext?.configured ? 'Yes' : 'No']]
    : [
      ['Status', ext.status],
      ['Source', ext.source],
      ['Measured from', ext.measuredFrom],
      ['Measured to', ext.measuredTo],
      ['Reachable %', pct(ext.uptimePercent)],
      ['Unreachable minutes', ext.downtimeMinutes],
      ['Outages', ext.outages.length],
      ['Outages while server was running', ext.outsideOnlyOutages],
      ['Poll coverage %', pct(ext.pollCoveragePercent)],
      ['Failed polls', ext.failedPolls],
    ]);
  add('23_external_uptime_outages.csv', ['Region', 'From', 'To', 'Ongoing', 'Duration (min)', 'Server heartbeat'],
    (ext?.outages || []).map((o) => [o.region, o.from, o.to, o.ongoing ? 'Yes' : 'No', o.durationMinutes, o.seenByHeartbeat ? 'Also down' : 'Running (outside-only)']));

  const blob = zip.generate({ type: 'blob', mimeType: 'application/zip', compression: 'DEFLATE' });
  saveAs(blob, `${fileStamp(report)}_CSV.zip`);
};
